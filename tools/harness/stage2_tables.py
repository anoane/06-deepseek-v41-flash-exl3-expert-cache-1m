#!/usr/bin/env python3
"""Stage-2 tables: one-factor arms against their layout's reference, per scenario group.

usage: stage2_tables.py --out FILE [--jsonl FILE] <results.jsonl or run dir> [...]

Arms: C12-R<n> -> C12 (reference of the C12 arms), C11-R<n> -> C11 (reference of the C11 arms); stage-1 / 0c lines
C12-<n> / C12-base-<n> -> C12@s1, C11-<n> -> C11@s1, A1M-<n> -> A1M (reference of the A1M-* arms); any other label
loses a trailing -<n> (C12-AA-2 -> C12-AA). Reference of an arm: C12-* -> C12, C11-* -> C11, A1M-* -> A1M.
Tables: processes (sizing, memory, VRAM, SSD reads), per group mean decode / prefill with the change against the
reference and the reference's spread (per-process means), greedy-token equality against the reference
(tokens_sha256_12 per job), a summary per arm (decode over S1-32K / S2-32K / S3 follow-ups; prefill S1-32K /
S1-128K; S3 follow-up TTFT) for the plan's win rule: both processes beat the reference by more than max(2%, the
reference's own spread).
"""
import json, os, re, statistics as st, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import h2h_tables as H


def arm_of(label):
    l = re.sub(r"-rerun$", "", label or "")
    if re.match(r"^C12-R\d+$", l):
        return "C12"
    if re.match(r"^C11-R\d+$", l):
        return "C11"
    if re.match(r"^C12-(base-)?\d+$", l):
        return "C12@s1"
    if re.match(r"^C11-\d+$", l):
        return "C11@s1"
    if re.match(r"^C10-\d+$", l):
        return "C10@s1"
    if re.match(r"^C8-\d+$", l):
        return "C8@s1"
    if re.match(r"^A1M-\d+$", l):
        return "A1M"
    return re.sub(r"-\d+$", "", l)


def ref_of(arm):
    if arm.startswith("C12-") or arm == "C12@s1":
        return "C12"
    if arm.startswith("C11-") or arm == "C11@s1":
        return "C11"
    if arm.startswith("C10-"):
        return "C10@s1"
    if arm.startswith("A1M-"):
        return "A1M"
    return None


def load(paths):
    recs = []
    for p in paths:
        fn = os.path.join(p, "results.jsonl") if os.path.isdir(p) else p
        for line in open(fn):
            try:
                r = json.loads(line)
            except ValueError:
                continue
            if r.get("status") == "skipped":
                continue
            r["_arm"] = arm_of(r.get("label"))
            recs.append(r)
    return recs


def pf_of(r):
    return r["delta_prefill_tps"] if r["group"].startswith(("S3", "S5")) and r["scenario"] != "S5b" else r["prefill_tps"]


def pct(v, rv):
    return f"{100 * (v / rv - 1):+.1f}%" if v is not None and rv else "-"


def seed_of(r):
    """the cold-fill seed the load printed (heat file or round robin), from the process log"""
    lf = r.get("log")
    return r.get("_seed", "")


def main():
    args = sys.argv[1:]
    out = jl = None
    paths = []
    i = 0
    while i < len(args):
        if args[i] == "--out":
            out = args[i + 1]; i += 2
        elif args[i] == "--jsonl":
            jl = args[i + 1]; i += 2
        else:
            paths.append(args[i]); i += 1
    recs = load(paths)
    H.arm_of = arm_of
    hrec = [r for r in recs if r.get("h2h") or r.get("longctx")]
    rows = H.rows_of(hrec, False)
    for r in rows:
        if r["group"].startswith("S4") and r["group"].endswith("decode"):
            r["prefill_tps"] = None
    groups = [x for x in H.ORDER if any(r["group"] == x for r in rows)] + \
        sorted({r["group"] for r in rows} - set(H.ORDER))
    arms = []
    for r in recs:
        if r["_arm"] not in arms:
            arms.append(r["_arm"])

    # per (group, arm): per-process means of decode, prefill, TTFT, hit
    pp = {}
    for r in rows:
        if r.get("excluded"):
            continue
        d = pp.setdefault((r["group"], r["arm"]), {}).setdefault(r["run_id"], ([], [], [], []))
        for j, v in enumerate((r["decode_tps"], pf_of(r), r["ttft_s"], r["hit"])):
            if v is not None:
                d[j].append(v)
    ppm = {k: {rid: tuple(st.mean(x) if x else None for x in v) for rid, v in d.items()} for k, d in pp.items()}

    def mean_of(gname, a, j):
        d = ppm.get((gname, a))
        v = [x[j] for x in (d or {}).values() if x[j] is not None]
        if not v:
            return None, None, None, 0
        return st.mean(v), min(v), max(v), len(v)

    def spread(s):
        return f"{100 * (s[2] - s[1]) / s[0]:.1f}% (n{s[3]})" if s[0] and s[3] > 1 else "-"

    L = ["# Stage 2 tables (generated by bench3/stage2_tables.py)", ""]
    L += ["## Processes", "",
          "| label | arm | status | load s | pool slots | staging | RAM tier GiB | n-gram GiB | unpinned GiB | "
          "SSD reads after load | max RSS GiB | min MemAvail GiB | nvsmi min free MiB | cgroup OOM kills |", "|" + "---|" * 14]
    for r in recs:
        ts = r.get("tier_sizing") or {}
        dv = (ts.get("devices") or [{}])[0] if ts else {}
        procs = H.g(r, "peaks", "host_end", "procs") or []
        rss = [p.get("hwm_gib") for p in procs if p.get("hwm_gib") is not None]
        lm = r.get("load_monitor") or {}
        mav = [x for x in (H.g(r, "batch_monitor", "min_mem_available_gib"), lm.get("min_mem_available_gib"))
               if isinstance(x, (int, float))]
        err = "" if r.get("status") == "ok" else ": " + str(r.get("error"))[:200].replace("|", "/").replace("\n", " ")
        L.append(f"| {r.get('label')} | {r['_arm']} | {r.get('status')}{err} | {H.f(H.g(r, 'load', 'seconds'))} | "
                 f"{dv.get('slots', '-')} | {dv.get('staging_slots', '-')} | {ts.get('ram_gib', '-')} | "
                 f"{ts.get('ngram_gib', '-')} | {ts.get('left_unpinned_gib', '-')} | "
                 f"{H.f(r.get('tier_ssd_reads_after_load'))} | {H.f(max(rss) if rss else None, 2)} | "
                 f"{H.f(min(mav) if mav else None, 1)} | {H.g(r, 'peaks', 'gpu_mem_min_free_mib')} | "
                 f"{H.g(r, 'peaks', 'cgroup_end', 'events_oom_kill')} |")
    L.append("")

    L += ["## Per scenario group: mean of the per-process means (tok/s), change against the reference", "",
          "Reference spread = (max - min) / mean of the reference's per-process means. Prefill of S3 / S5 turns = new "
          "rows / TTFT.", "",
          "| group | arm | n proc | decode | vs ref | prefill | vs ref | TTFT s | hit | ref decode spread | "
          "ref prefill spread |", "|" + "---|" * 11]
    for gname in groups:
        for a in arms:
            dm, pm, tm, hm = (mean_of(gname, a, j) for j in range(4))
            if dm[3] == 0 and pm[3] == 0:
                continue
            ref = ref_of(a)
            rd = mean_of(gname, ref, 0) if ref else (None,) * 4
            rp = mean_of(gname, ref, 1) if ref else (None,) * 4
            L.append(f"| {gname} | {a} | {dm[3] or pm[3]} | {H.f(dm[0], 2)} | {pct(dm[0], rd[0])} | {H.f(pm[0], 0)} | "
                     f"{pct(pm[0], rp[0])} | {H.f(tm[0], 2)} | {H.f(hm[0], 3)} | {spread(rd) if ref else '-'} | "
                     f"{spread(rp) if ref else '-'} |")
    L.append("")

    dig = {}
    for r in hrec:
        if r.get("status") != "ok":
            continue
        for sec in ("h2h", "longctx"):
            for m in (r.get(sec) or {}).get("jobs", []):
                dig.setdefault(r["_arm"], {}).setdefault((m["scenario"], m.get("turn")), set()).add(
                    m.get("tokens_sha256_12"))
    L += ["## Greedy tokens against the reference (jobs whose tokens_sha256_12 equals the reference's)", "",
          "| arm | reference | equal / compared | differing jobs |", "|---|---|---|---|"]
    for a in arms:
        ref = ref_of(a)
        if not ref or a == ref or a not in dig or ref not in dig:
            continue
        eq, n, diff = 0, 0, []
        for k, v in sorted(dig[a].items(), key = lambda x: str(x[0])):
            rv = dig[ref].get(k)
            if rv is None:
                continue
            n += 1
            if v == rv and len(v) == 1:
                eq += 1
            else:
                diff.append(f"{k[0]}{'_t' + str(k[1]) if k[1] else ''}")
        L.append(f"| {a} | {ref} | {eq} / {n} | {', '.join(diff) or '-'} |")
    L.append("")

    DG = ("S1-32K", "S2-32K", "S3-follow")

    def arm_decode(a):
        per = {}
        for gname in DG:
            for rid, v in (ppm.get((gname, a)) or {}).items():
                if v[0] is not None:
                    per.setdefault(rid, []).append(v[0])
        vals = [st.mean(v) for v in per.values() if len(v) == len(DG)]
        return (st.mean(vals) if vals else None), vals

    L += ["## Summary per arm", "",
          "decode = per process, the mean of S1-32K, S2-32K and S3 follow-up decode; prefill = S1-32K and S1-128K; "
          "S3 follow-up TTFT = mean TTFT of turns 2-6.", "",
          "| arm | ref | decode | vs ref | per-process decode | prefill 32K | vs ref | prefill 128K | vs ref | "
          "S3 follow TTFT s | vs ref |", "|" + "---|" * 11]
    for a in arms:
        d, per = arm_decode(a)
        ref = ref_of(a)
        rd = arm_decode(ref)[0] if ref else None
        p32, p128, ttf = mean_of("S1-32K", a, 1)[0], mean_of("S1-128K", a, 1)[0], mean_of("S3-follow", a, 2)[0]
        r32 = mean_of("S1-32K", ref, 1)[0] if ref else None
        r128 = mean_of("S1-128K", ref, 1)[0] if ref else None
        rtt = mean_of("S3-follow", ref, 2)[0] if ref else None
        L.append(f"| {a} | {ref or '-'} | {H.f(d, 2)} | {pct(d, rd)} | {' / '.join(f'{x:.2f}' for x in per) or '-'} | "
                 f"{H.f(p32, 0)} | {pct(p32, r32)} | {H.f(p128, 0)} | {pct(p128, r128)} | {H.f(ttf, 2)} | "
                 f"{pct(ttf, rtt)} |")
    L.append("")
    L += ["## Per scenario and arm (mean [min-max] over jobs)", ""] + H.scen_table(rows)[0] + [""]
    L += ["## S3 / S5 turns", ""] + H.turn_table(rows) + [""]
    L += ["## S5 collapse / recovery", ""] + H.recovery_table(rows) + [""]
    L += ["## Device time (H7)", ""] + H.devtime_table(hrec) + [""]
    q = [r for r in recs if r.get("quality")]
    if q:
        L += ["## Quality lines", ""]
        for r in q:
            L.append(f"- {r['label']}: {json.dumps(r.get('quality'))[:2000]}")
        L.append("")
    txt = "\n".join(L) + "\n"
    if out:
        open(out, "w").write(txt)
    else:
        print(txt)
    if jl:
        with open(jl, "w") as fh:
            for r in rows:
                fh.write(json.dumps({k: v for k, v in r.items() if k != "timeline"}) + "\n")


if __name__ == "__main__":
    main()
